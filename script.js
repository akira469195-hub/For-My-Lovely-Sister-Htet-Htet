const gallery = $("gallery");
const lightbox = $("lightbox");
const lightboxImage = $("lightboxImage");
const counter = $("photoCounter");

const totalPhotos = 14;
let currentIndex = 0;

// Create 13 photo thumbnails
for (let i = 1; i <= totalPhotos; i++) {
  const img = document.createElement("img");

  img.src = `images/${i}.jpg`;
  img.alt = `Memory ${i}`;
  img.className = "gallery-img";
  img.loading = "lazy";

  img.addEventListener("click", () => {
    openPhoto(i - 1);
  });

  gallery.appendChild(img);
}

// Open fullscreen photo
function openPhoto(index) {
  currentIndex = index;

  showPhoto();

  lightbox.classList.add("active");
  document.body.style.overflow = "hidden";
}

// Display selected photo
function showPhoto() {
  lightboxImage.src = `images/${currentIndex + 1}.jpg`;
  counter.textContent = `${currentIndex + 1} / ${totalPhotos}`;
}

// Next photo
function nextPhoto() {
  currentIndex = (currentIndex + 1) % totalPhotos;
  showPhoto();
}

// Previous photo
function prevPhoto() {
  currentIndex =
    (currentIndex - 1 + totalPhotos) % totalPhotos;

  showPhoto();
}

// Close fullscreen
function closePhoto() {
  lightbox.classList.remove("active");
  document.body.style.overflow = "";
}

// Button controls
$("nextPhoto").addEventListener("click", nextPhoto);
$("prevPhoto").addEventListener("click", prevPhoto);
$("closeLightbox").addEventListener("click", closePhoto);

// Close when clicking outside the image
lightbox.addEventListener("click", e => {
  if (e.target === lightbox) {
    closePhoto();
  }
});

// Keyboard controls
document.addEventListener("keydown", e => {
  if (!lightbox.classList.contains("active")) return;

  if (e.key === "ArrowRight") nextPhoto();
  if (e.key === "ArrowLeft") prevPhoto();
  if (e.key === "Escape") closePhoto();
});

// Mobile swipe controls
let touchStartX = 0;
let touchEndX = 0;

lightbox.addEventListener("touchstart", e => {
  touchStartX = e.changedTouches[0].screenX;
}, { passive: true });

lightbox.addEventListener("touchend", e => {
  touchEndX = e.changedTouches[0].screenX;

  const difference = touchEndX - touchStartX;

  if (Math.abs(difference) < 50) return;

  if (difference < 0) {
    nextPhoto();
  } else {
    prevPhoto();
  }
}, { passive: true });
